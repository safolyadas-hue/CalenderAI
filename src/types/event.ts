/** Event type literals */
export type EventType = 'wedding' | 'birthday' | 'community';

/** City classification for cost scaling */
export type CityTier = 'tier1_metro' | 'tier2_urban' | 'tier3_town';

/** Venue setting type */
export type SettingType = 'indoor' | 'outdoor' | 'hybrid';

/** Supported currency codes */
export type CurrencyCode = 'INR' | 'USD';

/**
 * Core context for an event plan — captures all user-provided details
 * that drive the decision engine's budget, timeline, vendor, and idea outputs.
 */
export interface EventContext {
  /** Unique identifier for this event plan */
  id: string;
  /** User-provided title for the event */
  title: string;
  /** Type of event being planned */
  eventType: EventType;
  /** Target date for the event in ISO YYYY-MM-DD format */
  eventDate: string;
  /** Expected number of guests */
  guestCount: number;
  /** Total budget allocated for the event */
  totalBudget: number;
  /** Currency used for all monetary values */
  currency: CurrencyCode;
  /** City tier affects venue pricing and vendor availability */
  cityTier: CityTier;
  /** Indoor, outdoor, or hybrid venue setting */
  setting: SettingType;
  /** Dietary preferences/restrictions (e.g., "vegetarian", "halal", "gluten-free") */
  dietaryPreferences: string[];
  /** Cultural or thematic style (e.g., "South Indian Traditional", "Bohemian") */
  culturalTheme: string;
  /** Free-form notes from the user */
  customNotes: string;
}

/**
 * A single budget line item with smart allocation logic.
 * Percentages across all categories must sum to 100%.
 */
export interface BudgetCategory {
  /** Unique identifier */
  id: string;
  /** Display name (e.g., "Venue & Decor", "Catering") */
  name: string;
  /** Percentage of total budget allocated to this category */
  percentage: number;
  /** Computed allocated amount = totalBudget * percentage / 100 */
  allocatedAmount: number;
  /** Actual amount spent so far */
  actualSpent: number;
  /** Priority tier for rebalancing logic */
  priority: 'essential' | 'important' | 'optional';
  /** AI-generated rationale explaining this allocation */
  rationale: string;
  /** If true, this category's allocation won't be auto-adjusted during rebalancing */
  isLocked: boolean;
}

/**
 * A single milestone in the event planning timeline.
 * Due dates are dynamically calculated based on the event date.
 */
export interface TimelineMilestone {
  /** Unique identifier */
  id: string;
  /** Short title for the milestone */
  title: string;
  /** Detailed description of what needs to be done */
  description: string;
  /** Number of days before the event this should be completed */
  daysBeforeEvent: number;
  /** Computed due date in ISO YYYY-MM-DD format */
  dueDate: string;
  /** Planning phase this milestone belongs to */
  phase:
    | 'Conceptualization'
    | 'Vendor Booking'
    | 'Logistics & Details'
    | 'Final Week'
    | 'Event Day';
  /** Priority level for scheduling and alerts */
  priority: 'critical' | 'high' | 'medium';
  /** Whether this milestone has been marked as completed */
  completed: boolean;
  /** Warning message if timeline is compressed and this task has high lead time */
  dependencyWarning?: string;
}

/**
 * A vendor or service provider entry with tracking and contract checklist.
 */
export interface VendorItem {
  /** Unique identifier */
  id: string;
  /** Vendor category (e.g., "Catering", "Photography") */
  category: string;
  /** Specific role name (e.g., "Lead Photographer", "Head Chef") */
  roleName: string;
  /** Lower bound of estimated cost range */
  estimatedCostMin: number;
  /** Upper bound of estimated cost range */
  estimatedCostMax: number;
  /** Actual quoted price once obtained */
  actualQuoted?: number;
  /** Current status in the vendor pipeline */
  status: 'shortlisted' | 'contacted' | 'booked' | 'paid';
  /** Key questions to ask this vendor during evaluation */
  questionsToAsk: string[];
  /** Contract checklist items to verify before signing */
  contractChecklist: { id: string; label: string; checked: boolean }[];
  /** Free-form notes about this vendor */
  notes: string;
}

/**
 * A personalized creative idea generated by the decision engine
 * based on the user's event context.
 */
export interface PersonalizedIdea {
  /** Unique identifier */
  id: string;
  /** Category grouping for the idea */
  category:
    | 'Theme & Decor'
    | 'Food & Beverage'
    | 'Guest Experience'
    | 'Sustainability & Cost-Saving';
  /** Short title for the idea */
  title: string;
  /** Detailed description of the idea */
  description: string;
  /** Expected impact on event quality or guest experience */
  estimatedImpact: string;
  /** Cost tier relative to the overall budget */
  costTier: 'low' | 'medium' | 'high';
  /** AI-generated explanation of why this idea fits the user's specific context */
  whyItFitsContext: string;
}

/**
 * A single message in the AI CoPilot conversation thread.
 */
export interface CoPilotMessage {
  /** Unique identifier */
  id: string;
  /** Message sender role */
  role: 'user' | 'assistant';
  /** Message text content */
  content: string;
  /** Optional suggested follow-up actions */
  suggestedActions?: string[];
  /** ISO timestamp of when this message was sent */
  timestamp: string;
}

/**
 * Complete event plan combining all generated outputs.
 * This is the top-level data structure for a fully computed plan.
 */
export interface EventPlan {
  /** The input context that generated this plan */
  context: EventContext;
  /** Smart budget breakdown across categories */
  budgetCategories: BudgetCategory[];
  /** Chronological planning timeline */
  timeline: TimelineMilestone[];
  /** Vendor checklist with contract items */
  vendors: VendorItem[];
  /** Personalized creative ideas */
  ideas: PersonalizedIdea[];
  /** Risk alerts flagged by the decision engine */
  riskAlerts: string[];
  /** Overall efficiency score (0-100) for the plan */
  efficiencyScore: number;
}
